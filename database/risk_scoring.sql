
-- FactoryPulse AI
-- Analytics 2: Explainable machine-risk scoring
-- All data is synthetic. Rules are demonstration thresholds,
-- not validated industrial safety limits or failure predictions.

WITH LATEST_DATA AS (
    SELECT MAX(READING_TIME) AS AS_OF_TIME
    FROM FACTORYPULSE.SENSOR_READINGS
),
SENSOR_METRICS AS (
    SELECT
        MACHINE_ID,
        SUM(CASE WHEN TEMPERATURE_C >= 78 THEN 1 ELSE 0 END)
            AS HIGH_TEMP_READINGS,
        SUM(CASE WHEN VIBRATION_MM_S >= 2.5 THEN 1 ELSE 0 END)
            AS HIGH_VIBRATION_READINGS
    FROM FACTORYPULSE.SENSOR_READINGS
    GROUP BY MACHINE_ID
),
DOWNTIME_METRICS AS (
    SELECT
        MACHINE_ID,
        COUNT(*) AS FAILURE_COUNT,
        SUM(SECONDS_BETWEEN(END_TIME, START_TIME)) / 3600.0
            AS DOWNTIME_HOURS
    FROM FACTORYPULSE.DOWNTIME_EVENTS
    GROUP BY MACHINE_ID
),
MAINTENANCE_METRICS AS (
    SELECT
        ML.MACHINE_ID,
        MAX(
            CASE
                WHEN ML.STATUS = 'Pending'
                 AND ML.MAINTENANCE_DATE < LD.AS_OF_TIME
                THEN 1
                ELSE 0
            END
        ) AS OVERDUE_MAINTENANCE
    FROM FACTORYPULSE.MAINTENANCE_LOGS ML
    CROSS JOIN LATEST_DATA LD
    GROUP BY ML.MACHINE_ID
),
MACHINE_FEATURES AS (
    SELECT
        M.MACHINE_ID,
        M.PLANT,
        M.MACHINE_TYPE,
        M.CRITICALITY,
        COALESCE(S.HIGH_TEMP_READINGS, 0) AS HIGH_TEMP_READINGS,
        COALESCE(S.HIGH_VIBRATION_READINGS, 0) AS HIGH_VIBRATION_READINGS,
        COALESCE(D.FAILURE_COUNT, 0) AS FAILURE_COUNT,
        COALESCE(D.DOWNTIME_HOURS, 0) AS DOWNTIME_HOURS,
        COALESCE(MM.OVERDUE_MAINTENANCE, 0) AS OVERDUE_MAINTENANCE
    FROM FACTORYPULSE.MACHINES M
    LEFT JOIN SENSOR_METRICS S
        ON M.MACHINE_ID = S.MACHINE_ID
    LEFT JOIN DOWNTIME_METRICS D
        ON M.MACHINE_ID = D.MACHINE_ID
    LEFT JOIN MAINTENANCE_METRICS MM
        ON M.MACHINE_ID = MM.MACHINE_ID
),
MACHINE_SCORES AS (
    SELECT
        F.*,
        CASE WHEN HIGH_TEMP_READINGS >= 5 THEN 25 ELSE 0 END
        + CASE WHEN HIGH_VIBRATION_READINGS >= 5 THEN 25 ELSE 0 END
        + CASE WHEN DOWNTIME_HOURS >= 12 THEN 30 ELSE 0 END
        + CASE WHEN OVERDUE_MAINTENANCE = 1 THEN 20 ELSE 0 END
            AS RISK_SCORE
    FROM MACHINE_FEATURES F
)
SELECT
    MACHINE_ID,
    PLANT,
    MACHINE_TYPE,
    CRITICALITY,
    HIGH_TEMP_READINGS,
    HIGH_VIBRATION_READINGS,
    FAILURE_COUNT,
    ROUND(DOWNTIME_HOURS, 2) AS DOWNTIME_HOURS,
    OVERDUE_MAINTENANCE,
    RISK_SCORE,
    CASE
        WHEN RISK_SCORE >= 70 THEN 'HIGH'
        WHEN RISK_SCORE >= 40 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS RISK_LEVEL,
    CASE
        WHEN HIGH_TEMP_READINGS >= 5
         AND HIGH_VIBRATION_READINGS >= 5
            THEN 'Inspect temperature and vibration; prioritize maintenance'
        WHEN HIGH_TEMP_READINGS >= 5
            THEN 'Investigate elevated temperature'
        WHEN HIGH_VIBRATION_READINGS >= 5
            THEN 'Inspect vibration levels'
        WHEN DOWNTIME_HOURS >= 12
            THEN 'Review significant downtime'
        WHEN OVERDUE_MAINTENANCE = 1
            THEN 'Review pending maintenance'
        ELSE 'Continue routine monitoring'
    END AS RECOMMENDED_ACTION
FROM MACHINE_SCORES
ORDER BY RISK_SCORE DESC, DOWNTIME_HOURS DESC;
